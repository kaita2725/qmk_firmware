#include QMK_KEYBOARD_H

enum layers {
    _BASE,
    _FN,
    _UTILS
};

// encoder button is the last layout arguments connected from B6 to diode to D5 on pro micro controller
enum custom_keycode {
  ENC_BTN = SAFE_RANGE
};

static bool menu_mode = false;
uint8_t menu_page = 0;
static uint8_t preview_layer_idx = 0;
static bool show_wpm_on_main = true;

static uint8_t last_row = 0;
static uint8_t last_col = 0;
static uint16_t last_keycode = 0;

typedef struct menu_node menu_node_t;

struct menu_node {
    const char *name;
    const menu_node_t *parent;
    const menu_node_t *children;
    uint8_t child_count;
    void (*action)(void);
    void (*adjust_action)(bool clockwise);
};

extern const menu_node_t root_menu[];
extern const menu_node_t audio_menu[];
extern const menu_node_t brightness_menu[];

#define ROOT_MENU_SIZE 6

const menu_node_t *current_menu = root_menu;
uint8_t current_menu_size = ROOT_MENU_SIZE;
bool is_adjusting_value = false;

const menu_node_t *previous_menu = NULL;
uint8_t previous_menu_size = 0;

void adjust_audio_volume(bool clockwise){
    tap_code(clockwise ? KC_VOLU : KC_VOLD);
};

void audio_toggle (void){
    tap_code(KC_MUTE);
};

void adjust_screen_brightness(bool clockwise){
    tap_code(clockwise ? KC_BRIU : KC_BRID);
};

void menu_action_view_layouts(void){
    preview_layer_idx = 0;
};

void adjust_preview_layer(bool clockwise){
    if(clockwise){
        if(preview_layer_idx < 2) preview_layer_idx++;
    }else {
        if(preview_layer_idx > 0) preview_layer_idx--;
    }
};

void menu_action_debug(void){
};

void adjust_debug_view(bool clockwise){
};

void menu_action_toggle_wpm(void) {
    show_wpm_on_main = !show_wpm_on_main;
};

void menu_action_back(void){
    if (previous_menu != NULL) {
        current_menu = previous_menu;
        current_menu_size = previous_menu_size;

        previous_menu = NULL;
        previous_menu_size = 0;
    } else {
        // Ultimate fallback
        current_menu = root_menu;
        current_menu_size = ROOT_MENU_SIZE;
    }
    menu_page = 0;
    oled_clear();
};

void menu_action_exit(void){
    menu_mode = false;
    oled_clear();
};

