uint8_t get_ping_pong_frame(void){
    static uint16_t anim_timer = 0;
    static uint8_t  virtual_frame = 0;

    // Advance frame every 83ms (~12 FPS)
    if (timer_elapsed(anim_timer) > 83) {
        anim_timer = timer_read();
        virtual_frame = (virtual_frame + 1) % 12; // Total loop length is 12 frames
    }
    if (virtual_frame >= 6) {
        return 11 - virtual_frame; // Triggers reverse order (5, 4, 3, 2, 1, 0)
    }
    return virtual_frame;
};

void draw_left_frame(void) {
    // oled_write_raw_P(anim_frames[0], 64);
    uint8_t frame = get_ping_pong_frame();
    for (uint8_t page = 0; page < 8; page++) {
        oled_set_cursor(0, page);
        oled_write_raw_P(anim_frames[frame]+(page*64), 64);
    }
};

void draw_right_frame(void){
    for (uint8_t page = 0; page < 8; page++){
        oled_set_cursor(11, page);
        char buf[17] = {0};
        led_t led_state = host_keyboard_led_state();
        switch(page){
            case 0:
                snprintf(buf, sizeof(buf), "          ");
                break;
            case 1:
                uint8_t layer = get_highest_layer(layer_state);
                switch (layer) {
                    case _BASE:  snprintf(buf, sizeof(buf),"BASE "); break;
                    case _FN:    snprintf(buf, sizeof(buf),"FN   "); break;
                    case _UTILS: snprintf(buf, sizeof(buf),"UTILS"); break;
                    default:     snprintf(buf, sizeof(buf),"UNKNOWN"); break;
                }
                break;
            case 2:
                if (show_wpm_on_main) {
                    snprintf(buf, sizeof(buf), "%d WPM", get_current_wpm());
                }
                break;
            case 3:
                snprintf(buf, sizeof(buf), led_state.caps_lock ? "CAPS" : "    ");
                break;
            case 4:
                snprintf(buf, sizeof(buf), led_state.caps_lock ? "CAPS" : "    ");
                break;
            default:
                snprintf(buf, sizeof(buf), "          ");
                break;
        }
        oled_write(buf, false);
    }
};

bool oled_task_user(void){
    static bool last_menu_mode = false;
    if (menu_mode != last_menu_mode) {
        oled_clear();
        last_menu_mode = menu_mode;
    }
    if(menu_mode){
        oled_set_cursor(0, 0);
        if(is_adjusting_value){
            if(current_menu[menu_page].adjust_action == &adjust_preview_layer){
                draw_matrix_schematic(preview_layer_idx);

                oled_write_ln_P(PSTR("----------------"), false);
                oled_write_ln_P(PSTR("Turn Enc: Next/Prev | Press Enc: Back"), false);
            } else if(current_menu[menu_page].adjust_action == &adjust_debug_view){
                draw_debug_monitor();

                oled_write_ln_P(PSTR("----------------"), false);
                oled_write_ln_P(PSTR("Press Enc: Back"), false);
            } else {
                char title_buf[21];
                snprintf(title_buf, sizeof(title_buf), "TWEAK: %s", current_menu[menu_page].name);
                oled_write_ln(title_buf, false);

                oled_write_ln_P(PSTR("----------------"), false);
                oled_write_ln_P(PSTR("Turn Enc: Change"), false);
                oled_write_ln_P(PSTR("Press Enc: Save/Back"), false);
            }
        } else {
            if(current_menu == root_menu){
                oled_write_ln_P(PSTR("==== MAIN MENU ===="), false);
            }else {
                oled_write_ln_P(PSTR("==== SUB MENU ===="), false);
            }

            uint8_t start_item = 0;
            if (menu_page >= 3) {
                start_item = menu_page - 2;
            }

            uint8_t end_item = start_item + 3;
            if (end_item > current_menu_size) {
                end_item = current_menu_size;
            }

            for (uint8_t i = start_item; i < end_item; i++){
                char row_buf[21];
                snprintf(row_buf, sizeof(row_buf), "%s %s", (menu_page == i) ? ">":" ", current_menu[i].name);
                oled_write_ln(row_buf, false);
            }
            for (uint8_t i = (end_item - start_item) + 1; i < 8; i++) {
                oled_write_ln_P(PSTR("                    "), false);
            }
        }
    }else{
        draw_left_frame();
        draw_right_frame();
    }
    oled_render();
    return false;
};
